    private suspend fun searchYouTubeTracksByFilter(
        query: String,
        contentFilter: String,
        genreHint: String = "",
        maxResults: Int = 14
    ): List<MusicTrackPreset> {
        val cleanQuery = sanitizeMusicQuery(query)
        if (cleanQuery.isBlank()) return emptyList()
        val currentYear = Calendar.getInstance().get(Calendar.YEAR)

        return youTubeQuerySemaphore.withPermit {
            withTimeoutOrNull(9_000L) {
                withContext(Dispatchers.IO) {
                    runCatching {
                        ensureNewPipeReady()
                        val extractor = ServiceList.YouTube.getSearchExtractor(
                            cleanQuery,
                            listOf(contentFilter),
                            ""
                        )
                        extractor.fetchPage()
                        val items = extractor.initialPage.items
                        val results = ArrayList<MusicTrackPreset>(maxResults)
                        val seenVideoIds = HashSet<String>()
                        val isClipQuery = contentFilter == YoutubeSearchQueryHandlerFactory.MUSIC_VIDEOS ||
                            contentFilter == YoutubeSearchQueryHandlerFactory.VIDEOS

                        for (infoItem in items) {
                            if (results.size >= maxResults) break
                            val item = infoItem as? StreamInfoItem ?: continue
                            val streamType = item.streamType
                            if (streamType == StreamType.LIVE_STREAM ||
                                streamType == StreamType.AUDIO_LIVE_STREAM ||
                                streamType == StreamType.POST_LIVE_STREAM ||
                                streamType == StreamType.POST_LIVE_AUDIO_STREAM
                            ) {
                                continue
                            }
                            if (runCatching { item.isShortFormContent }.getOrDefault(false)) continue

                            val durationSec = item.duration
                            if (!isValidIndividualTrackDuration(durationSec)) continue

                            val rawTitle = item.name?.trim().orEmpty()
                            if (rawTitle.isEmpty()) continue
                            if (isLongMixOrCompilation(rawTitle, item.uploaderName)) continue

                            val videoId = extractYouTubeVideoId(item.url) ?: continue
                            if (!seenVideoIds.add(videoId)) continue

                            val (cleanTitle, cleanArtist) = cleanYouTubeTitleAndArtist(rawTitle, item.uploaderName)
                            val thumb = pickBestThumbnailUrl(
                                runCatching { item.thumbnails }.getOrNull(),
                                fallbackVideoId = videoId
                            )
                            val recency = computeRecencyScore(
                                textualUploadDate = runCatching { item.textualUploadDate }.getOrNull(),
                                title = rawTitle,
                                currentYear = currentYear
                            )
                            val kind = if (isClipQuery) MusicItemKind.CLIP else MusicItemKind.SONG

                            results.add(
                                MusicTrackPreset(
                                    id = "ytm_$videoId",
                                    title = cleanTitle,
                                    artist = cleanArtist,
                                    album = if (isClipQuery) "Clip Officiel" else "Single",
                                    genre = genreHint,
                                    streamUrl = "$YT_MUSIC_LAZY_SCHEME$videoId",
                                    artworkUrl = thumb,
                                    durationSeconds = durationSec.coerceAtMost(Int.MAX_VALUE.toLong()).toInt(),
                                    providerName = PROVIDER_YOUTUBE_MUSIC,
                                    isPipedLazy = true,
                                    isTrending = recency >= 50,
                                    itemKind = kind,
                                    recencyScore = recency
                                )
                            )
                        }
                        results
                    }.getOrDefault(emptyList())
                }
            } ?: emptyList()
        }
    }

    private suspend fun searchYouTubeCollectionsByFilter(
        query: String,
        contentFilter: String,
        genreHint: String = "",
        maxResults: Int = 6
    ): List<MusicTrackPreset> {
        val cleanQuery = sanitizeMusicQuery(query)
        if (cleanQuery.isBlank()) return emptyList()
        val currentYear = Calendar.getInstance().get(Calendar.YEAR)
        val isAlbumFilter = contentFilter == YoutubeSearchQueryHandlerFactory.MUSIC_ALBUMS

        return youTubeQuerySemaphore.withPermit {
            withTimeoutOrNull(9_000L) {
                withContext(Dispatchers.IO) {
                    runCatching {
                        ensureNewPipeReady()
                        val extractor = ServiceList.YouTube.getSearchExtractor(
                            cleanQuery,
                            listOf(contentFilter),
                            ""
                        )
