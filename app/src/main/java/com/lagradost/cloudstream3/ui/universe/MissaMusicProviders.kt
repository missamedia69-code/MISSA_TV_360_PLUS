    /**
     * Prioritizes lightweight, low-latency progressive HTTP audio streams (`45..96 kbps` Opus /
     * HE-AAC sweet spot around `64 kbps`) so tracks start almost instantaneously with minimal
     * bandwidth and zero initial buffering lag.
     */
    fun sortNewPipeAudioStreams(streams: List<AudioStream>): List<String> {
        fun lightnessBitrateBand(bitrate: Int): Int = when {
            bitrate in 45..96 -> 4   // Ultra-fast low-latency sweet spot (e.g. itag 250 ~64k Opus, itag 139 48k M4A)
            bitrate in 97..135 -> 3  // Standard 128k M4A/Opus
            bitrate in 24..44 -> 2   // Ultra-light fallback
            bitrate <= 0 -> 2        // Unknown bitrate
            else -> 1                // Heavy 160k+ stream (last resort to minimize latency)
        }

        return streams
            .filter { stream ->
                stream.isUrl &&
                    !stream.content.isNullOrBlank() &&
                    stream.deliveryMethod != DeliveryMethod.TORRENT
            }
            .sortedWith(
                compareByDescending<AudioStream> { it.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP }
                    .thenByDescending { lightnessBitrateBand(it.averageBitrate) }
                    .thenByDescending { it.format == MediaFormat.M4A || it.format == MediaFormat.WEBMA }
                    .thenBy { kotlin.math.abs(it.averageBitrate.coerceAtLeast(64) - 64) }
            )
            .map { it.content }
            .distinct()
    }

    /**
     * Selects lightweight, fast-starting YouTube video streams (`240p..360p` preferred, `480p`
     * secondary) for the top MP3/Clip player monitor to minimize buffering latency:
     * 1. [Pair.first] = progressive muxed MP4 (`video + audio` in a single HTTP stream),
     * 2. [Pair.second] = progressive H.264/MP4 video-only stream (merged with cached audio in ExoPlayer).
     */
    fun selectBestVideoStreams(
        muxedStreams: List<VideoStream>,
        videoOnlyStreams: List<VideoStream>
    ): Pair<String?, String?> {
        val resDigitsRegex = Regex("(\\d{3,4})p", RegexOption.IGNORE_CASE)
        fun effectiveHeight(stream: VideoStream): Int {
            if (stream.height > 0) return stream.height
            return resDigitsRegex.find(stream.getResolution())
                ?.groupValues
                ?.getOrNull(1)
                ?.toIntOrNull()
                ?: 0
        }

        fun heightScore(height: Int): Int = when {
            height in 240..360 -> 5 // Lightweight 240p/360p fast-start target
            height in 361..480 -> 4 // 480p secondary
            height in 144..239 -> 3 // Ultra-light fallback
            height in 481..720 -> 2 // 720p only when no lighter stream exists
            else -> 0
        }

        val bestMuxed = muxedStreams
            .filter { stream ->
                stream.isUrl &&
                    !stream.content.isNullOrBlank() &&
                    stream.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP &&
                    (stream.format == MediaFormat.MPEG_4 || stream.format == null)
            }
            .sortedWith(
                compareByDescending<VideoStream> { heightScore(effectiveHeight(it)) }
                    .thenBy { kotlin.math.abs(effectiveHeight(it).coerceAtLeast(360) - 360) }
            )
            .firstOrNull()
            ?.content

        val bestVideoOnly = videoOnlyStreams
            .filter { stream ->
                val codecLower = stream.codec?.lowercase(Locale.ROOT).orEmpty()
                val h = effectiveHeight(stream)
                stream.isUrl &&
                    !stream.content.isNullOrBlank() &&
                    stream.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP &&
                    (stream.format == MediaFormat.MPEG_4 || codecLower.startsWith("avc")) &&
                    h in 144..720
            }
            .sortedWith(
                compareByDescending<VideoStream> { heightScore(effectiveHeight(it)) }
                    .thenByDescending { it.codec?.lowercase(Locale.ROOT)?.startsWith("avc") == true }
                    .thenBy { kotlin.math.abs(effectiveHeight(it).coerceAtLeast(360) - 360) }
            )
            .firstOrNull()
            ?.content

        return bestMuxed to bestVideoOnly
    }

    /**
     * Builds an ordered failover chain of lightweight video clip candidates (`240p..360p`
     * progressive muxed first, lightweight H.264/VP9 video-only merged with cached audio, and
     * 360p-capped adaptive HLS `.m3u8`) for ultra-low startup latency.
     */
    fun buildVideoClipCandidates(
        muxedStreams: List<VideoStream>,
        videoOnlyStreams: List<VideoStream>,
        hlsUrl: String?,
        hasAudioStreams: Boolean
    ): List<VideoClipCandidate> {
        val resDigitsRegex = Regex("(\\d{3,4})p", RegexOption.IGNORE_CASE)
        fun effectiveHeight(stream: VideoStream): Int {
            if (stream.height > 0) return stream.height
            return resDigitsRegex.find(stream.getResolution())
                ?.groupValues
                ?.getOrNull(1)
                ?.toIntOrNull()
                ?: 0
        }

        fun heightScore(height: Int): Int = when {
            height in 240..360 -> 5
            height in 361..480 -> 4
            height in 144..239 -> 3
            height in 481..720 -> 2
            else -> 1 // Unknown height when itagItem == null
        }

        val candidates = ArrayList<VideoClipCandidate>(6)
        val seenUrls = HashSet<String>()

        // 1. Progressive muxed MP4/WebM streams (360p preferred: single HTTP stream with video + audio)
        muxedStreams
            .filter { s ->
                s.isUrl &&
                    !s.content.isNullOrBlank() &&
                    s.deliveryMethod != DeliveryMethod.TORRENT
            }
            .sortedWith(
                compareByDescending<VideoStream> { s -> s.format == MediaFormat.MPEG_4 }
                    .thenByDescending { s -> heightScore(effectiveHeight(s)) }
                    .thenBy { s -> kotlin.math.abs(effectiveHeight(s).coerceAtLeast(360) - 360) }
            )
            .take(2)
            .forEach { s ->
                if (seenUrls.add(s.content)) {
                    candidates.add(VideoClipCandidate(VideoClipSourceKind.MUXED_PROGRESSIVE, s.content))
                }
            }

        // 2. Apple iOS / visionOS HLS `.m3u8` master playlist (video + audio, instant mid-track seek)
        val cleanHls = hlsUrl?.trim().orEmpty()
        if (cleanHls.startsWith("http", ignoreCase = true) && seenUrls.add(cleanHls)) {
            candidates.add(VideoClipCandidate(VideoClipSourceKind.HLS_ADAPTIVE, cleanHls))
        }

        // 3. Adaptive lightweight video-only streams (240p..480p) merged with cached audio
        if (hasAudioStreams) {
            videoOnlyStreams
                .filter { s ->
                    val h = effectiveHeight(s)
                    s.isUrl &&
                        !s.content.isNullOrBlank() &&
                        s.deliveryMethod != DeliveryMethod.TORRENT &&
                        (h == 0 || h in 144..720)
                }
                .sortedWith(
                    compareByDescending<VideoStream> { s ->
                        val c = s.codec?.lowercase(Locale.ROOT).orEmpty()
                        when {
                            c.startsWith("avc") || s.format == MediaFormat.MPEG_4 -> 3
                            c.startsWith("vp9") || c.startsWith("vp09") || s.format == MediaFormat.WEBM -> 2
                            else -> 1
                        }
                    }
                        .thenByDescending { s -> heightScore(effectiveHeight(s)) }
                        .thenBy { s -> kotlin.math.abs(effectiveHeight(s).coerceAtLeast(360) - 360) }
                )
                .take(3)
                .forEach { s ->
                    if (seenUrls.add(s.content)) {
                        candidates.add(VideoClipCandidate(VideoClipSourceKind.VIDEO_ONLY_MERGED, s.content))
                    }
                }
        }

        return candidates
    }

    fun invalidateCachedAudio(streamUrlOrVideoId: String) {
        val videoId = extractYouTubeVideoId(streamUrlOrVideoId) ?: streamUrlOrVideoId.trim()
        if (videoId.isEmpty()) return
        synchronized(audioCacheLock) {
            resolvedAudioCache.remove(videoId)
        }
    }

    fun hasCachedAudioUrl(streamUrlOrVideoId: String): Boolean {
        val videoId = extractYouTubeVideoId(streamUrlOrVideoId) ?: return false
        val now = System.currentTimeMillis()
        synchronized(audioCacheLock) {
            val cached = resolvedAudioCache[videoId] ?: return false
            return cached.expiresAtMs > now && cached.media.hasPlayableStream
        }
    }

    private suspend fun resolveYouTubeMediaStreams(videoId: String): ResolvedYouTubeMedia {
        if (videoId.isBlank()) return ResolvedYouTubeMedia(emptyList())
        val now = System.currentTimeMillis()
        var existingDeferred: CompletableDeferred<ResolvedYouTubeMedia>? = null
        var ownedDeferred: CompletableDeferred<ResolvedYouTubeMedia>? = null

        synchronized(audioCacheLock) {
            val cached = resolvedAudioCache[videoId]
            if (cached != null && cached.expiresAtMs > now && cached.media.hasPlayableStream) {
                return cached.media
            }
            val inFlight = inFlightAudioResolutions[videoId]
            if (inFlight != null) {
                existingDeferred = inFlight
            } else {
                ownedDeferred = CompletableDeferred()
                inFlightAudioResolutions[videoId] = ownedDeferred!!
            }
        }

        existingDeferred?.let { return it.await() }

        val resolved = withTimeoutOrNull(11_000L) {
            withContext(Dispatchers.IO) {
                runCatching {
                    ensureNewPipeReady()
                    val watchUrl = "https://www.youtube.com/watch?v=$videoId"
                    val streamInfo = StreamInfo.getInfo(ServiceList.YouTube, watchUrl)
                    val sortedAudio = sortNewPipeAudioStreams(streamInfo.audioStreams.orEmpty())
                    val muxedList = streamInfo.videoStreams.orEmpty()
                    val videoOnlyList = streamInfo.videoOnlyStreams.orEmpty()
                    val (muxedVideo, videoOnly) = selectBestVideoStreams(
                        muxedStreams = muxedList,
                        videoOnlyStreams = videoOnlyList
                    )
                    val cleanHls = streamInfo.hlsUrl?.trim()?.takeIf {
                        it.startsWith("http", ignoreCase = true)
                    }
                    val finalAudio = if (sortedAudio.isNotEmpty()) {
                        sortedAudio
                    } else if (cleanHls != null) {
                        listOf(cleanHls)
                    } else {
                        emptyList()
                    }
                    val videoCandidates = buildVideoClipCandidates(
                        muxedStreams = muxedList,
                        videoOnlyStreams = videoOnlyList,
                        hlsUrl = cleanHls,
                        hasAudioStreams = sortedAudio.isNotEmpty()
                    )
                    ResolvedYouTubeMedia(
                        audioUrls = finalAudio,
                        muxedVideoUrl = muxedVideo,
                        videoOnlyUrl = videoOnly,
                        hlsVideoUrl = cleanHls,
                        videoCandidates = videoCandidates
                    )
                }.getOrDefault(ResolvedYouTubeMedia(emptyList()))
            }
        } ?: ResolvedYouTubeMedia(emptyList())

        synchronized(audioCacheLock) {
            inFlightAudioResolutions.remove(videoId)
            if (resolved.hasPlayableStream) {
                if (resolvedAudioCache.size >= MAX_AUDIO_CACHE_ENTRIES) {
                    resolvedAudioCache.entries.firstOrNull()?.key?.let { resolvedAudioCache.remove(it) }
                }
                resolvedAudioCache[videoId] = CachedResolvedMedia(
                    media = resolved,
                    expiresAtMs = System.currentTimeMillis() + RESOLVED_AUDIO_TTL_MS
                )
            }
        }
        ownedDeferred?.complete(resolved)
        return resolved
    }

    /**
     * When the user activates Video Mode while listening to a YouTube Music `SONG` ("Artist - Topic"
     * static cover art track), searches for the matching Official Music Video (`MUSIC_VIDEOS`) so
     * the top monitor displays the actual moving video clip rather than a static cover frame.
     */
    suspend fun resolveOfficialVideoClipMediaIfAvailable(track: MusicTrackPreset): ResolvedYouTubeMedia? {
        val songVideoId = extractYouTubeVideoId(track.streamUrl).orEmpty()
        val query = listOf(track.artist.trim(), track.title.trim())
            .filter { it.isNotBlank() }
            .joinToString(" ")
            .trim()
        if (query.length < 3) return null

        val cacheKey = "${normalizeForMatch(track.artist)}|${normalizeForMatch(track.title)}"
        val cachedClipVideoId = synchronized(artworkCacheLock) { officialClipVideoIdCache[cacheKey] }
        if (cachedClipVideoId == "__none__") return null
        if (!cachedClipVideoId.isNullOrBlank()) {
            val media = resolveYouTubeMediaStreams(cachedClipVideoId)
            if (media.hasPlayableVideo) return media
        }

        val foundClip = withTimeoutOrNull(5_500L) {
            val clips = searchYouTubeTracksByFilter(
                query = "$query clip officiel",
                contentFilter = YoutubeSearchQueryHandlerFactory.MUSIC_VIDEOS,
                maxResults = 5
            ).ifEmpty {
                searchYouTubeTracksByFilter(
                    query = "$query official video",
                    contentFilter = YoutubeSearchQueryHandlerFactory.VIDEOS,
                    maxResults = 5
                )
            }
            clips.firstOrNull { cand ->
                val cid = extractYouTubeVideoId(cand.streamUrl).orEmpty()
                cid.isNotBlank() && cid != songVideoId
            }
        }

        val clipId = foundClip?.let { extractYouTubeVideoId(it.streamUrl) }.orEmpty()
        synchronized(artworkCacheLock) {
            if (officialClipVideoIdCache.size >= 64) {
                officialClipVideoIdCache.entries.firstOrNull()?.key?.let { officialClipVideoIdCache.remove(it) }
            }
            officialClipVideoIdCache[cacheKey] = clipId.ifBlank { "__none__" }
        }
        if (clipId.isBlank()) return null

        val clipMedia = resolveYouTubeMediaStreams(clipId)
        return clipMedia.takeIf { it.hasPlayableVideo }
    }

    suspend fun resolvePlayableYouTubeMedia(
        streamUrl: String,
        fallbackUrls: List<String> = emptyList()
    ): ResolvedYouTubeMedia {
        if (isLazyYouTubeAudioScheme(streamUrl)) {
            val videoId = extractYouTubeVideoId(streamUrl).orEmpty()
            return resolveYouTubeMediaStreams(videoId)
        }
        val directUrls = (listOf(streamUrl) + fallbackUrls).filter {
            it.startsWith("https://", ignoreCase = true) || it.startsWith("http://", ignoreCase = true)
        }.distinct()
        return ResolvedYouTubeMedia(audioUrls = directUrls)
    }

    suspend fun resolvePlayableAudioUrls(
