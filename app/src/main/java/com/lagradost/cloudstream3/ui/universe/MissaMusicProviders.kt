    /**
     * Strictly blocks DJ mixes, non-stop compilations, megamixes, hour-long sets, and non-music
     * videos while preserving individual songs, clips, and official radio/single remixes.
     */
    fun isLongMixOrCompilation(rawTitle: String, rawUploader: String? = null): Boolean {
        val combined = listOfNotNull(rawTitle, rawUploader).joinToString(" ").trim()
        if (combined.isEmpty()) return true
        if (nonMusicNoiseRegex.containsMatchIn(combined)) return true
        if (longMixOrCompilationRegex.containsMatchIn(rawTitle)) return true
        if (!rawUploader.isNullOrBlank() && Regex("\\bdj\\b.*\\bmix", RegexOption.IGNORE_CASE).containsMatchIn("$rawUploader $rawTitle")) {
            return true
        }
        return false
    }

    fun isValidIndividualTrackDuration(durationSeconds: Long): Boolean {
        return durationSeconds in MIN_TRACK_DURATION_SECONDS..MAX_TRACK_DURATION_SECONDS
    }

    fun isValidYouTubePlaylistOrAlbum(
        name: String,
        uploader: String?,
        url: String,
        streamCount: Long,
        playlistType: PlaylistInfo.PlaylistType? = PlaylistInfo.PlaylistType.NORMAL
    ): Boolean {
        if (name.isBlank() || url.isBlank()) return false
        if (playlistType != null && playlistType != PlaylistInfo.PlaylistType.NORMAL) return false
        if (url.contains("list=RD", ignoreCase = true) || url.contains("list=UL", ignoreCase = true)) {
            return false
        }
        if (streamCount == 1L || streamCount > 300L) return false
        if (isLongMixOrCompilation(name, uploader)) return false
        return true
    }

