    suspend fun extractYouTubeAlbumOrPlaylistTracks(
        playlistOrLazyUrl: String,
        fallbackAlbumTitle: String = "",
        fallbackArtist: String = "",
        fallbackArtworkUrl: String? = null,
        fallbackGenre: String = ""
    ): List<MusicTrackPreset> = withContext(Dispatchers.IO) {
        val cleanUrl = playlistOrLazyUrl
            .removePrefix(YT_PLAYLIST_LAZY_SCHEME)
            .removePrefix("YTPLAYLIST://")
            .trim()
        if (cleanUrl.isEmpty()) return@withContext emptyList()

        val now = System.currentTimeMillis()
        synchronized(searchCacheLock) {
            val cached = playlistTracksCache[cleanUrl]
            if (cached != null && cached.expiresAtMs > now && cached.items.isNotEmpty()) {
                return@withContext cached.items
            }
        }

        val extracted = withTimeoutOrNull(11_000L) {
            runCatching {
                ensureNewPipeReady()
                val info = PlaylistInfo.getInfo(ServiceList.YouTube, cleanUrl)
                val albumCover = pickBestThumbnailUrl(runCatching { info.thumbnails }.getOrNull())
                    ?: upgradeToAuthenticHdArtworkUrl(fallbackArtworkUrl)
                val albumTitle = info.name?.trim()?.takeIf { it.isNotEmpty() } ?: fallbackAlbumTitle
                val albumUploader = info.uploaderName
                    ?.replace(ytTopicSuffixRegex, "")
                    ?.replace(ytChannelSuffixRegex, "")
                    ?.trim()
                    .orEmpty()
                    .ifEmpty { fallbackArtist }

                val streamItems = info.relatedItems.orEmpty()
                val tracks = ArrayList<MusicTrackPreset>(streamItems.size)
                val seenIds = HashSet<String>()

                val isAlbumStyleCover = isStudioSquareArtworkUrl(albumCover)
                for (streamItem in streamItems) {
                    if (tracks.size >= 80) break
                    val st = streamItem.streamType
                    if (st == StreamType.LIVE_STREAM || st == StreamType.AUDIO_LIVE_STREAM) continue
                    val dur = streamItem.duration
                    // Album intros/interludes may be ~40s; still strictly block long mixes > 9 min
                    if (dur in 1L..34L || dur > MAX_TRACK_DURATION_SECONDS) continue
                    val rawTitle = streamItem.name?.trim().orEmpty()
                    if (rawTitle.isEmpty() || isLongMixOrCompilation(rawTitle, streamItem.uploaderName)) continue

                    val videoId = extractYouTubeVideoId(streamItem.url) ?: continue
                    if (!seenIds.add(videoId)) continue

                    val (cleanTitle, parsedArtist) = cleanYouTubeTitleAndArtist(
                        rawTitle,
                        streamItem.uploaderName ?: albumUploader
                    )
                    val trackArt = if (isAlbumStyleCover) {
                        albumCover
                    } else {
                        pickBestThumbnailUrl(
                            runCatching { streamItem.thumbnails }.getOrNull(),
                            fallbackVideoId = videoId
                        ) ?: albumCover
                    }

                    tracks.add(
                        MusicTrackPreset(
                            id = "ytm_$videoId",
                            title = cleanTitle,
                            artist = parsedArtist.ifEmpty { albumUploader },
                            album = albumTitle,
                            genre = fallbackGenre,
                            streamUrl = "$YT_MUSIC_LAZY_SCHEME$videoId",
                            artworkUrl = trackArt,
                            durationSeconds = dur.coerceAtLeast(0L).coerceAtMost(Int.MAX_VALUE.toLong()).toInt(),
                            providerName = PROVIDER_YOUTUBE_MUSIC,
                            isPipedLazy = true,
                            itemKind = if (isAlbumStyleCover) MusicItemKind.SONG else MusicItemKind.CLIP
                        )
                    )
                }
                tracks.toList()
            }.getOrDefault(emptyList())
        } ?: emptyList()

        if (extracted.isNotEmpty()) {
            synchronized(searchCacheLock) {
                if (playlistTracksCache.size >= 24) {
                    playlistTracksCache.entries.firstOrNull()?.key?.let { playlistTracksCache.remove(it) }
                }
                playlistTracksCache[cleanUrl] = CachedSearchBatch(extracted, now + PLAYLIST_CACHE_TTL_MS)
            }
        }
        extracted
    }

