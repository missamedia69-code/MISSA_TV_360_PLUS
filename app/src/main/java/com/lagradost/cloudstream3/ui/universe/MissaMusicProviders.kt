    /**
     * Returns true when [url] points to a genuine 1:1 studio album/single cover
     * (YouTube Music `googleusercontent.com` / `ggpht.com` or Apple/iTunes `mzstatic.com`).
     */
    fun isStudioSquareArtworkUrl(url: String?): Boolean {
        if (url.isNullOrBlank()) return false
        val lower = url.lowercase(Locale.ROOT)
        return lower.contains("googleusercontent.com") ||
            lower.contains("ggpht.com") ||
            lower.contains("mzstatic.com")
    }

    /**
     * Upgrades YouTube Music square covers (`=w60-h60` / `=w120-h120`) to crisp `544x544` studio
     * covers and replaces 4:3 letterboxed YouTube video thumbnails (`hqdefault.jpg`) with clean
     * borderless 16:9 HD thumbnails (`mqdefault.jpg` / `hq720.jpg`).
     */
    fun upgradeToAuthenticHdArtworkUrl(rawUrl: String?): String? {
        val trimmed = rawUrl?.trim()?.takeIf {
            it.startsWith("https://", ignoreCase = true) || it.startsWith("http://", ignoreCase = true)
        } ?: return null

        val httpsUrl = if (trimmed.startsWith("http://", ignoreCase = true)) {
            "https://" + trimmed.removePrefix("http://").removePrefix("HTTP://")
        } else {
            trimmed
        }

        val lower = httpsUrl.lowercase(Locale.ROOT)
        if (lower.contains("googleusercontent.com") || lower.contains("ggpht.com")) {
            return if (googleThumbSizeSuffixRegex.containsMatchIn(httpsUrl)) {
                httpsUrl.replace(googleThumbSizeSuffixRegex, "=w544-h544-l90-rj")
            } else if (!httpsUrl.contains("=w")) {
                "$httpsUrl=w544-h544-l90-rj"
            } else {
                httpsUrl
            }
        }

        if (lower.contains("mzstatic.com")) {
            return httpsUrl
                .replace("100x100bb", "600x600bb")
                .replace("200x200bb", "600x600bb")
        }

        if (lower.contains("ytimg.com") || lower.contains("img.youtube.com")) {
            val withoutCropQuery = httpsUrl.substringBefore("?sqp=").substringBefore("&sqp=")
            if (ytFourByThreeBlackBarRegex.containsMatchIn(withoutCropQuery)) {
                return withoutCropQuery.replace(ytFourByThreeBlackBarRegex, "/mqdefault.jpg")
            }
            return withoutCropQuery
        }

        return httpsUrl
    }

    internal fun pickBestThumbnailUrl(thumbnails: List<Image>?, fallbackVideoId: String? = null): String? {
        if (!thumbnails.isNullOrEmpty()) {
            // Prefer square studio covers (`googleusercontent.com`) first, then highest-area borderless HD frame
            val studioSquare = thumbnails
                .firstOrNull { isStudioSquareArtworkUrl(it.url) }
                ?.url
            if (!studioSquare.isNullOrBlank()) {
                return upgradeToAuthenticHdArtworkUrl(studioSquare)
            }

            val best = thumbnails
                .filter { it.url.startsWith("http", ignoreCase = true) }
                .sortedWith(
                    compareByDescending<Image> { img ->
                        val u = img.url.lowercase(Locale.ROOT)
                        when {
                            u.contains("mqdefault") -> 3
                            u.contains("hqdefault") || u.contains("sddefault") -> 2
                            u.contains("hq720") || u.contains("maxresdefault") -> 1
                            else -> 1
                        }
                    }.thenBy {
                        val w = it.width.coerceAtLeast(1)
                        val h = it.height.coerceAtLeast(1)
                        kotlin.math.abs(w * h - 320 * 180)
                    }
                )
                .firstOrNull()
                ?.url
            val upgraded = upgradeToAuthenticHdArtworkUrl(best)
            if (!upgraded.isNullOrBlank()) return upgraded
        }
        return fallbackVideoId?.let { "https://i.ytimg.com/vi/$it/mqdefault.jpg" }
    }

    private fun artworkMatchKey(artist: String, title: String): String {
        val normArtist = normalizeForMatch(artist).split(' ').take(3).joinToString(" ")
        val normTitle = normalizeForMatch(title)
            .replace(Regex("\\b(feat|ft|clip|officiel|official|video|audio)\\b.*$"), "")
            .trim()
        return "$normArtist|$normTitle"
    }

    /**
     * Transfers authentic 1:1 `googleusercontent.com` studio covers discovered on `MUSIC_SONGS`
     * or `MUSIC_ALBUMS` onto matching `MUSIC_VIDEOS` clips in the same batch.
     */
    fun crossMatchStudioCovers(tracks: List<MusicTrackPreset>): List<MusicTrackPreset> {
        if (tracks.isEmpty()) return tracks
        val coverByArtistAndTitle = HashMap<String, String>()
        val coverByExactTitle = HashMap<String, String>()

        for (track in tracks) {
            val art = track.artworkUrl ?: continue
            if (!isStudioSquareArtworkUrl(art)) continue
            val upgraded = upgradeToAuthenticHdArtworkUrl(art) ?: continue
            val fullKey = artworkMatchKey(track.artist, track.title)
            if (fullKey.length > 3 && !coverByArtistAndTitle.containsKey(fullKey)) {
                coverByArtistAndTitle[fullKey] = upgraded
            }
            val titleOnly = normalizeForMatch(track.title)
            if (titleOnly.length >= 5 && !coverByExactTitle.containsKey(titleOnly)) {
                coverByExactTitle[titleOnly] = upgraded
            }
        }

        if (coverByArtistAndTitle.isEmpty()) return tracks

        return tracks.map { track ->
            if (isStudioSquareArtworkUrl(track.artworkUrl)) {
                track.copy(artworkUrl = upgradeToAuthenticHdArtworkUrl(track.artworkUrl))
            } else {
                val matched = coverByArtistAndTitle[artworkMatchKey(track.artist, track.title)]
                    ?: (if (track.artist.isBlank()) coverByExactTitle[normalizeForMatch(track.title)] else null)
                if (!matched.isNullOrBlank()) {
                    track.copy(artworkUrl = matched)
                } else {
                    track.copy(artworkUrl = upgradeToAuthenticHdArtworkUrl(track.artworkUrl))
                }
            }
        }
    }

    internal fun parseItunesCoverArtJson(
        jsonBody: String,
        expectedArtist: String,
        expectedTitle: String
    ): String? = runCatching {
        val root = JSONObject(jsonBody)
        val results = root.optJSONArray("results") ?: return null
        val normArtistTokens = normalizeForMatch(expectedArtist).split(' ').filter { it.length >= 2 }
        val normTitleTokens = normalizeForMatch(expectedTitle)
            .replace(Regex("\\b(feat|ft|remix)\\b.*$"), "")
            .trim()
            .split(' ')
            .filter { it.length >= 2 }
        if (normTitleTokens.isEmpty()) return null

        for (i in 0 until results.length()) {
            val obj = results.optJSONObject(i) ?: continue
            val candidateArtist = normalizeForMatch(obj.optString("artistName"))
            val candidateTitle = normalizeForMatch(
                obj.optString("trackName").ifBlank { obj.optString("collectionName") }
            )
            val art100 = obj.optString("artworkUrl100").trim()
            if (art100.isEmpty()) continue

            val titleMatches = normTitleTokens.all { candidateTitle.contains(it) }
            val artistMatches = normArtistTokens.isEmpty() || normArtistTokens.any { candidateArtist.contains(it) }
            if (titleMatches && artistMatches) {
                return upgradeToAuthenticHdArtworkUrl(art100)
            }
        }
        null
    }.getOrNull()

    private suspend fun lookupAuthenticStudioCoverUrl(artist: String, title: String): String? {
        if (title.isBlank()) return null
        val cacheKey = artworkMatchKey(artist, title)
        synchronized(artworkCacheLock) {
            val cached = studioArtworkCache[cacheKey]
            if (cached != null) return cached.ifEmpty { null }
        }

        val resolved = coverLookupSemaphore.withPermit {
            withTimeoutOrNull(2_400L) {
                withContext(Dispatchers.IO) {
                    runCatching {
                        val term = listOf(artist.trim(), title.trim())
                            .filter { it.isNotEmpty() }
                            .joinToString(" ")
                        val encoded = URLEncoder.encode(term, "UTF-8")
                        val url = "https://itunes.apple.com/search?term=$encoded&media=music&entity=song&limit=4"
                        val req = Request.Builder()
                            .url(url)
                            .header("Accept", "application/json")
                            .build()
                        metadataHttpClient.newCall(req).execute().use { resp ->
                            if (!resp.isSuccessful) return@use null
                            val body = resp.body?.string() ?: return@use null
                            parseItunesCoverArtJson(body, artist, title)
                        }
                    }.getOrNull()
                }
            }
        }

        synchronized(artworkCacheLock) {
            if (studioArtworkCache.size >= MAX_ARTWORK_CACHE_ENTRIES) {
                val eldest = studioArtworkCache.entries.firstOrNull()?.key
                if (eldest != null) studioArtworkCache.remove(eldest)
            }
            studioArtworkCache[cacheKey] = resolved.orEmpty()
        }
        return resolved
    }

    /**
     * Enriches up to [maxLookups] clips that lack a 1:1 studio cover with verified 600x600
     * record-label artwork while keeping 100% YouTube audio playback.
     */
    suspend fun enrichAuthenticCoverArtworks(
        tracks: List<MusicTrackPreset>,
        maxLookups: Int = 14
    ): List<MusicTrackPreset> = coroutineScope {
        val crossMatched = crossMatchStudioCovers(tracks)
        var lookupsScheduled = 0
        crossMatched.map { track ->
            if (!isStudioSquareArtworkUrl(track.artworkUrl) &&
                !track.isAlbumOrPlaylist() &&
                lookupsScheduled < maxLookups
            ) {
                lookupsScheduled++
                async {
                    val studioArt = lookupAuthenticStudioCoverUrl(track.artist, track.title)
                    if (!studioArt.isNullOrBlank()) {
                        track.copy(artworkUrl = studioArt)
                    } else {
                        track
                    }
                }
            } else {
                async { track }
            }
        }.awaitAll()
    }

