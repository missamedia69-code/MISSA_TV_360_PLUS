/**
 * Exclusive YouTube Music Engine for the **Musiques** universe (`id = "music"`).
 *
 * Architectural guarantees:
 * 1. **YouTube as sole music source** (`ServiceList.YouTube` via NewPipeExtractor — zero third-party
 *    radio/podcast/server mixing).
 * 2. **User-chosen Musical Styles** drive discovery of the **most recent** Clips, Singles, Albums
 *    and Playlists on YouTube.
 * 3. **Strict Anti-Long-Mix policy**: individual tracks/clips are bounded to `55s..540s` (max 9 min)
 *    and DJ mixes, non-stop compilations, megamixes, mixtapes, and autogenerated YouTube mixes are
 *    systematically excluded.
 * 4. **Authentic HD Cover Artworks**: upgrades YouTube Music `googleusercontent.com` / `ggpht.com`
 *    studio sleeves to `544x544`, cross-matches Clips with studio single covers, avoids 4:3
 *    black-bar `hqdefault.jpg` thumbnails, and enriches unmatched clips with verified 600x600
 *    record-label cover metadata.
 * 5. **Fast Loading & Instant Playback**: NewPipe warm-up, progressive 2-wave style loading,
 *    search/playlist caches, and coalesced 2h30 LRU caching of resolved YouTube audio stream URLs.
 */
