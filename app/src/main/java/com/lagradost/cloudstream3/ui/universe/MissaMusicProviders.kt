    private val leadingTrailingNoiseRegex = Regex("^[\\s'\"‘’“”`´«»]+|[\\s'\"‘’“”`´«»]+$")
    private val multiWhitespaceRegex = Regex("\\s+")
    private val diacriticsRegex = Regex("\\p{InCombiningDiacriticalMarks}+")
    private val nonAlphaNumSplitRegex = Regex("[^a-z0-9]+")

    fun sanitizeMusicQuery(raw: String): String {
        val normalizedQuotes = raw
            .replace('’', '\'')
            .replace('‘', '\'')
            .replace('“', '"')
            .replace('”', '"')
        return normalizedQuotes
            .replace(leadingTrailingNoiseRegex, "")
            .replace(multiWhitespaceRegex, " ")
            .trim()
    }

    fun normalizeForMatch(raw: String): String {
        val decomposed = Normalizer.normalize(
            raw.lowercase(Locale.ROOT)
                .replace('’', '\'')
                .replace('‘', '\''),
            Normalizer.Form.NFD
        )
        return decomposed
            .replace(diacriticsRegex, "")
            .replace(nonAlphaNumSplitRegex, " ")
            .replace(multiWhitespaceRegex, " ")
            .trim()
    }

