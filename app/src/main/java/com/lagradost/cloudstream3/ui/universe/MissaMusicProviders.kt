                        val results = ArrayList<MusicTrackPreset>(maxResults)
                        val seenUrls = HashSet<String>()

                        for (infoItem in items) {
                            if (results.size >= maxResults) break
                            val item = infoItem as? PlaylistInfoItem ?: continue
                            val playlistUrl = item.url?.trim().orEmpty()
                            val rawTitle = item.name?.trim().orEmpty()
                            val streamCount = runCatching { item.streamCount }.getOrDefault(0L)
                            val playlistType = runCatching { item.playlistType }.getOrNull()

                            if (!isValidYouTubePlaylistOrAlbum(
                                    name = rawTitle,
                                    uploader = item.uploaderName,
                                    url = playlistUrl,
                                    streamCount = streamCount,
                                    playlistType = playlistType
                                )
                            ) {
                                continue
                            }
                            if (!seenUrls.add(playlistUrl)) continue

                            val (cleanTitle, cleanArtist) = cleanYouTubeTitleAndArtist(rawTitle, item.uploaderName)
                            val thumb = pickBestThumbnailUrl(runCatching { item.thumbnails }.getOrNull())
                            val recency = computeRecencyScore(
                                textualUploadDate = null,
                                title = rawTitle,
                                currentYear = currentYear
                            ) + 55 // Official YouTube Music albums/playlists for currentYear query
                            val itemKind = if (isAlbumFilter) MusicItemKind.ALBUM else MusicItemKind.PLAYLIST
                            val safeCount = streamCount.coerceIn(0L, 200L).toInt()

                            results.add(
                                MusicTrackPreset(
                                    id = "ytpl_${playlistUrl.hashCode()}",
                                    title = cleanTitle,
                                    artist = cleanArtist,
                                    album = if (isAlbumFilter) "Album Officiel" else "Playlist Officielle",
                                    genre = genreHint,
                                    streamUrl = "$YT_PLAYLIST_LAZY_SCHEME$playlistUrl",
                                    artworkUrl = thumb,
                                    durationSeconds = 0,
                                    providerName = PROVIDER_YOUTUBE_MUSIC,
                                    isPipedLazy = true,
                                    isTrending = true,
                                    itemKind = itemKind,
                                    trackCount = safeCount,
                                    recencyScore = recency
                                )
                            )
                        }
                        results
                    }.getOrDefault(emptyList())
                }
            } ?: emptyList()
        }
    }

    // -------------------------------------------------------------------------
    // Album / Playlist Track Queue Extraction
    // -------------------------------------------------------------------------

    suspend fun extractYouTubeAlbumOrPlaylistTracks(
        playlistOrLazyUrl: String,
        fallbackAlbumTitle: String = "",
        fallbackArtist: String = "",
        fallbackArtworkUrl: String? = null,
        fallbackGenre: String = ""
    ): List<MusicTrackPreset> = withContext(Dispatchers.IO) {
        val cleanUrl = playlistOrLazyUrl
            .removePrefix(YT_PLAYLIST_LAZY_SCHEME)
            .removePrefix("YTPLAYLIST://")
            .trim()
        if (cleanUrl.isEmpty()) return@withContext emptyList()

        val now = System.currentTimeMillis()
        synchronized(searchCacheLock) {
            val cached = playlistTracksCache[cleanUrl]
            if (cached != null && cached.expiresAtMs > now && cached.items.isNotEmpty()) {
                return@withContext cached.items
            }
        }

        val extracted = withTimeoutOrNull(11_000L) {
            runCatching {
                ensureNewPipeReady()
                val info = PlaylistInfo.getInfo(ServiceList.YouTube, cleanUrl)
                val albumCover = pickBestThumbnailUrl(runCatching { info.thumbnails }.getOrNull())
                    ?: upgradeToAuthenticHdArtworkUrl(fallbackArtworkUrl)
                val albumTitle = info.name?.trim()?.takeIf { it.isNotEmpty() } ?: fallbackAlbumTitle
                val albumUploader = info.uploaderName
                    ?.replace(ytTopicSuffixRegex, "")
                    ?.replace(ytChannelSuffixRegex, "")
                    ?.trim()
                    .orEmpty()
                    .ifEmpty { fallbackArtist }

                val streamItems = info.relatedItems.orEmpty()
                val tracks = ArrayList<MusicTrackPreset>(streamItems.size)
                val seenIds = HashSet<String>()

                for (streamItem in streamItems) {
                    if (tracks.size >= 50) break
                    val st = streamItem.streamType
                    if (st == StreamType.LIVE_STREAM || st == StreamType.AUDIO_LIVE_STREAM) continue
                    val dur = streamItem.duration
                    // Album intros/interludes may be ~40s; still strictly block long mixes > 9 min
                    if (dur in 1L..34L || dur > MAX_TRACK_DURATION_SECONDS) continue
                    val rawTitle = streamItem.name?.trim().orEmpty()
                    if (rawTitle.isEmpty() || isLongMixOrCompilation(rawTitle, streamItem.uploaderName)) continue

                    val videoId = extractYouTubeVideoId(streamItem.url) ?: continue
                    if (!seenIds.add(videoId)) continue

                    val (cleanTitle, parsedArtist) = cleanYouTubeTitleAndArtist(
                        rawTitle,
                        streamItem.uploaderName ?: albumUploader
                    )
                    val trackArt = if (isStudioSquareArtworkUrl(albumCover)) {
                        albumCover
                    } else {
                        pickBestThumbnailUrl(
                            runCatching { streamItem.thumbnails }.getOrNull(),
                            fallbackVideoId = videoId
                        ) ?: albumCover
                    }

                    tracks.add(
                        MusicTrackPreset(
                            id = "ytm_$videoId",
                            title = cleanTitle,
                            artist = parsedArtist.ifEmpty { albumUploader },
                            album = albumTitle,
                            genre = fallbackGenre,
                            streamUrl = "$YT_MUSIC_LAZY_SCHEME$videoId",
                            artworkUrl = trackArt,
                            durationSeconds = dur.coerceAtLeast(0L).coerceAtMost(Int.MAX_VALUE.toLong()).toInt(),
                            providerName = PROVIDER_YOUTUBE_MUSIC,
                            isPipedLazy = true,
                            itemKind = MusicItemKind.SONG
                        )
                    )
                }
                tracks.toList()
            }.getOrDefault(emptyList())
        } ?: emptyList()

        if (extracted.isNotEmpty()) {
            synchronized(searchCacheLock) {
                if (playlistTracksCache.size >= 24) {
                    playlistTracksCache.entries.firstOrNull()?.key?.let { playlistTracksCache.remove(it) }
                }
                playlistTracksCache[cleanUrl] = CachedSearchBatch(extracted, now + PLAYLIST_CACHE_TTL_MS)
            }
        }
        extracted
    }

    // -------------------------------------------------------------------------
    // Audio Stream Resolution + 2h30 Coalesced LRU Cache
    // -------------------------------------------------------------------------

    fun sortNewPipeAudioStreams(streams: List<AudioStream>): List<String> {
        return streams
            .filter { stream ->
                stream.isUrl &&
                    !stream.content.isNullOrBlank() &&
                    stream.deliveryMethod != DeliveryMethod.TORRENT
            }
            .sortedWith(
                compareByDescending<AudioStream> { it.deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP }
                    .thenByDescending { it.format == MediaFormat.M4A }
                    .thenByDescending { it.averageBitrate }
            )
            .map { it.content }
            .distinct()
    }

    fun invalidateCachedAudio(streamUrlOrVideoId: String) {
        val videoId = extractYouTubeVideoId(streamUrlOrVideoId) ?: streamUrlOrVideoId.trim()
        if (videoId.isEmpty()) return
        synchronized(audioCacheLock) {
            resolvedAudioCache.remove(videoId)
        }
    }

    fun hasCachedAudioUrl(streamUrlOrVideoId: String): Boolean {
        val videoId = extractYouTubeVideoId(streamUrlOrVideoId) ?: return false
        val now = System.currentTimeMillis()
        synchronized(audioCacheLock) {
            val cached = resolvedAudioCache[videoId] ?: return false
            return cached.expiresAtMs > now && cached.urls.isNotEmpty()
        }
    }

    private suspend fun resolveYouTubeAudioStreamUrls(videoId: String): List<String> {
        if (videoId.isBlank()) return emptyList()
        val now = System.currentTimeMillis()
        var existingDeferred: CompletableDeferred<List<String>>? = null
        var ownedDeferred: CompletableDeferred<List<String>>? = null

        synchronized(audioCacheLock) {
            val cached = resolvedAudioCache[videoId]
            if (cached != null && cached.expiresAtMs > now && cached.urls.isNotEmpty()) {
                return cached.urls
            }
            val inFlight = inFlightAudioResolutions[videoId]
            if (inFlight != null) {
                existingDeferred = inFlight
            } else {
                ownedDeferred = CompletableDeferred()
                inFlightAudioResolutions[videoId] = ownedDeferred!!
            }
        }

        existingDeferred?.let { return it.await() }

        val resolved = withTimeoutOrNull(11_000L) {
            withContext(Dispatchers.IO) {
                runCatching {
                    ensureNewPipeReady()
                    val watchUrl = "https://www.youtube.com/watch?v=$videoId"
                    val streamInfo = StreamInfo.getInfo(ServiceList.YouTube, watchUrl)
                    val sortedAudio = sortNewPipeAudioStreams(streamInfo.audioStreams.orEmpty())
                    if (sortedAudio.isNotEmpty()) {
                        sortedAudio
                    } else {
                        val hls = streamInfo.hlsUrl?.trim().orEmpty()
                        if (hls.startsWith("http", ignoreCase = true)) listOf(hls) else emptyList()
                    }
                }.getOrDefault(emptyList())
            }
        } ?: emptyList()

        synchronized(audioCacheLock) {
            inFlightAudioResolutions.remove(videoId)
            if (resolved.isNotEmpty()) {
                if (resolvedAudioCache.size >= MAX_AUDIO_CACHE_ENTRIES) {
                    resolvedAudioCache.entries.firstOrNull()?.key?.let { resolvedAudioCache.remove(it) }
                }
                resolvedAudioCache[videoId] = CachedResolvedAudio(
                    urls = resolved,
                    expiresAtMs = System.currentTimeMillis() + RESOLVED_AUDIO_TTL_MS
                )
            }
        }
        ownedDeferred?.complete(resolved)
        return resolved
    }

    suspend fun resolvePlayableAudioUrls(
        streamUrl: String,
        fallbackUrls: List<String> = emptyList()
    ): List<String> {
        if (isLazyYouTubeAudioScheme(streamUrl)) {
            val videoId = extractYouTubeVideoId(streamUrl).orEmpty()
            return resolveYouTubeAudioStreamUrls(videoId)
        }
        return (listOf(streamUrl) + fallbackUrls).filter {
            it.startsWith("https://", ignoreCase = true) || it.startsWith("http://", ignoreCase = true)
        }.distinct()
    }

