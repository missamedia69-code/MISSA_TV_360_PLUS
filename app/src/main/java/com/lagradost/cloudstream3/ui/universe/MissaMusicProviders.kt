    fun matchesTrackQuery(track: MusicTrackPreset, rawQuery: String): Boolean {
        val cleanQuery = sanitizeMusicQuery(rawQuery)
        if (cleanQuery.isEmpty()) return true
        val normQuery = normalizeForMatch(cleanQuery)
        if (normQuery.isEmpty()) return true

        val haystack = normalizeForMatch(
            "${track.artist} ${track.title} ${track.album} ${track.genre}"
        )
        if (haystack.contains(normQuery)) return true

        val tokens = normQuery.split(' ').filter { it.isNotEmpty() }
        if (tokens.isEmpty()) return true
        return tokens.all { token -> haystack.contains(token) }
    }

    fun rankTracksForQuery(tracks: List<MusicTrackPreset>, rawQuery: String): List<MusicTrackPreset> {
        val normQuery = normalizeForMatch(sanitizeMusicQuery(rawQuery))
        if (normQuery.isEmpty()) return tracks
        val tokens = normQuery.split(' ').filter { it.isNotEmpty() }

        return tracks.sortedByDescending { track ->
            val normArtist = normalizeForMatch(track.artist)
            val normTitle = normalizeForMatch(track.title)
            val normCombined = "$normArtist $normTitle".trim()
            var score = 0
            if (normArtist == normQuery) score += 120
            if (normTitle == normQuery) score += 110
            if (normCombined.contains(normQuery)) score += 80
            if (normArtist.startsWith(normQuery)) score += 55
            if (normTitle.startsWith(normQuery)) score += 45
            val matchedTokens = tokens.count { tok -> normCombined.contains(tok) }
            score += matchedTokens * 20
            if (isStudioSquareArtworkUrl(track.artworkUrl)) score += 18
            score += (track.recencyScore / 5)
            score
        }
    }

