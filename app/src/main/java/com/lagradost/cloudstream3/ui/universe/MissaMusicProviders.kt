    // Progressive Style-Driven YouTube Catalog & On-Demand Search
    // -------------------------------------------------------------------------

    private fun deduplicateAndOrderCatalog(batches: List<MusicTrackPreset>): List<MusicTrackPreset> {
        val crossMatched = crossMatchStudioCovers(batches)
        val merged = ArrayList<MusicTrackPreset>(crossMatched.size)
        val seenIds = HashSet<String>()
        val seenNormalizedTitleArtist = HashSet<String>()

        val sorted = crossMatched.sortedWith(
            compareByDescending<MusicTrackPreset> { it.recencyScore }
                .thenByDescending { isStudioSquareArtworkUrl(it.artworkUrl) }
                .thenByDescending { !it.artworkUrl.isNullOrBlank() }
        )

        for (track in sorted) {
            if (track.title.isBlank() || track.streamUrl.isBlank()) continue
            if (!seenIds.add(track.id)) continue
            val sig = "${track.itemKind.name}|${normalizeForMatch(track.artist)}|${normalizeForMatch(track.title)}"
            if (!seenNormalizedTitleArtist.add(sig)) continue
            merged.add(track)
        }
        return merged
    }

    /**
     * Loads the newest YouTube Clips, Studio Singles, Official Albums, and Playlists matching
     * the user's chosen [styleIds].
     *
     * Emits **Wave 1** (newest Singles & Official Clips) immediately via [onFirstWaveReady] so
     * shelves render rapidly, then completes **Wave 2** (Official Albums, Playlists & verified
     * studio cover enrichment).
     */
    suspend fun fetchStyleCatalogProgressive(
        styleIds: Collection<String>?,
        onFirstWaveReady: ((List<MusicTrackPreset>) -> Unit)? = null
    ): List<MusicTrackPreset> = coroutineScope {
        val selectedStyles = resolveSelectedStyles(styleIds)
        val currentYear = Calendar.getInstance().get(Calendar.YEAR)
        val perStyleSongs = if (selectedStyles.size <= 2) 12 else 8
        val perStyleClips = if (selectedStyles.size <= 2) 12 else 8
        val perStyleCollections = if (selectedStyles.size <= 2) 5 else 3

        // Wave 1: Newest studio songs (1:1 covers) + newest official clips in parallel
        val wave1Jobs = selectedStyles.flatMap { style ->
            listOf(
                async {
                    searchYouTubeTracksByFilter(
                        query = "${style.songsKeywords} $currentYear",
                        contentFilter = YoutubeSearchQueryHandlerFactory.MUSIC_SONGS,
                        genreHint = style.genreTag,
                        maxResults = perStyleSongs
                    )
                },
                async {
                    searchYouTubeTracksByFilter(
                        query = "${style.clipsKeywords} $currentYear",
                        contentFilter = YoutubeSearchQueryHandlerFactory.MUSIC_VIDEOS,
                        genreHint = style.genreTag,
                        maxResults = perStyleClips
                    )
                }
            )
        }

        // Launch Wave 2 concurrently so it finishes right after Wave 1 without idle waiting
        val wave2CollectionJobs = selectedStyles.flatMap { style ->
            listOf(
                async {
                    searchYouTubeCollectionsByFilter(
                        query = "${style.albumsKeywords} $currentYear",
                        contentFilter = YoutubeSearchQueryHandlerFactory.MUSIC_ALBUMS,
                        genreHint = style.genreTag,
                        maxResults = perStyleCollections
                    )
                },
                async {
                    searchYouTubeCollectionsByFilter(
                        query = "${style.playlistsKeywords} $currentYear",
                        contentFilter = YoutubeSearchQueryHandlerFactory.MUSIC_PLAYLISTS,
                        genreHint = style.genreTag,
                        maxResults = perStyleCollections
                    )
                }
            )
        }

        val wave1Raw = wave1Jobs.awaitAll().flatten()
        val wave1Ordered = deduplicateAndOrderCatalog(wave1Raw)
        if (wave1Ordered.isNotEmpty()) {
            onFirstWaveReady?.invoke(wave1Ordered)
        }

        val wave2Collections = wave2CollectionJobs.awaitAll().flatten()
        val combined = deduplicateAndOrderCatalog(wave1Ordered + wave2Collections)
        enrichAuthenticCoverArtworks(combined, maxLookups = 12)
    }

    /**
     * Live on-demand YouTube search returning matching Singles, Official Clips, Albums, and
     * Playlists while strictly excluding long DJ mixes.
     */
    suspend fun searchAllMusicServers(query: String): List<MusicTrackPreset> = coroutineScope {
        val cleanQuery = sanitizeMusicQuery(query)
        if (cleanQuery.length < 2) return@coroutineScope emptyList()

        val cacheKey = normalizeForMatch(cleanQuery)
        val now = System.currentTimeMillis()
        synchronized(searchCacheLock) {
            val cached = searchResultsCache[cacheKey]
            if (cached != null && cached.expiresAtMs > now && cached.items.isNotEmpty()) {
                return@coroutineScope cached.items
            }
        }

        val jobs = listOf(
            async {
                searchYouTubeTracksByFilter(
                    query = cleanQuery,
                    contentFilter = YoutubeSearchQueryHandlerFactory.MUSIC_SONGS,
                    maxResults = 16
                )
            },
            async {
                searchYouTubeTracksByFilter(
                    query = cleanQuery,
                    contentFilter = YoutubeSearchQueryHandlerFactory.MUSIC_VIDEOS,
                    maxResults = 14
                )
            },
            async {
                searchYouTubeCollectionsByFilter(
                    query = cleanQuery,
                    contentFilter = YoutubeSearchQueryHandlerFactory.MUSIC_ALBUMS,
                    maxResults = 5
                )
            },
            async {
                searchYouTubeCollectionsByFilter(
                    query = cleanQuery,
                    contentFilter = YoutubeSearchQueryHandlerFactory.MUSIC_PLAYLISTS,
                    maxResults = 4
                )
            }
        )

        var merged = deduplicateAndOrderCatalog(jobs.awaitAll().flatten())
        if (merged.isEmpty()) {
            val videoFallback = searchYouTubeTracksByFilter(
                query = "$cleanQuery clip officiel",
                contentFilter = YoutubeSearchQueryHandlerFactory.VIDEOS,
                maxResults = 14
            )
            merged = deduplicateAndOrderCatalog(videoFallback)
        }

        val ranked = rankTracksForQuery(
            enrichAuthenticCoverArtworks(merged, maxLookups = 8),
            cleanQuery
        )

        if (ranked.isNotEmpty()) {
            synchronized(searchCacheLock) {
                if (searchResultsCache.size >= 24) {
                    searchResultsCache.entries.firstOrNull()?.key?.let { searchResultsCache.remove(it) }
                }
                searchResultsCache[cacheKey] = CachedSearchBatch(ranked, now + SEARCH_CACHE_TTL_MS)
            }
        }
        ranked
    }
